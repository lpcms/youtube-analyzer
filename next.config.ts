import type { NextConfig } from "next";

const nextConfig: NextConfig = {
  reactStrictMode: true,
  // Playwright ходит на 127.0.0.1, а дев-сервер Next по умолчанию считает
  // такой хост посторонним и блокирует свои dev-ресурсы. На прод не влияет.
  allowedDevOrigins: ["127.0.0.1"],
  /**
   * Папка сборки — из переменной, чтобы прогон E2E не пересекался
   * с дев-сервером, запущенным руками.
   *
   * Одного лишь отдельного порта мало: Next отказывается поднимать второй
   * dev-сервер из той же папки, потому что замок лежит внутри distDir.
   * Со своей папкой прогон живёт рядом с рабочим сервером и не трогает
   * ни его, ни рабочую базу.
   */
  distDir: process.env.NEXT_DIST_DIR ?? ".next",
};

export default nextConfig;
